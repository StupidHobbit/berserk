pub fn unique_effect(card: &Card) -> Option<usize> {
    // These effects are authored against the base scan. Don't misalign them on a
    // different alternate/full-art scan; missing-art variants do reuse base art.
    if !matches!(card.rarity, 3 | 4)
        || !(card.alt.is_empty() || card.alt == "f" || card.uses_base_art())
    {
        return None;
    }
    UNIQUE_EFFECTS
        .iter()
        .position(|e| e.set_id == card.set_id && e.number == card.number)
}
